// Verificación de navegador opcional. Instalar Playwright o indicar PLAYWRIGHT_MODULE_DIR.
const { chromium } = require(require.resolve('playwright', { paths: [process.env.PLAYWRIGHT_MODULE_DIR || process.cwd()] }));
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
(async () => {
  const env = Object.fromEntries(fs.readFileSync('.env', 'utf8').split(/\r?\n/).filter((s) => s && !s.startsWith('#') && s.includes('=')).map((s) => { const i=s.indexOf('='); return [s.slice(0,i),s.slice(i+1)]; }));
  const executablePath = process.env.CHROME_BIN || ['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Google/Chrome/Application/chrome.exe'].find(fs.existsSync);
  const browser = await chromium.launch({ headless: true, executablePath });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  const screenshots = process.env.SKINMARKET_SCREENSHOTS || 'docs/screenshots';
  fs.mkdirSync(screenshots, { recursive: true });
  const shot = (name, fullPage = false) => page.screenshot({ path: path.join(screenshots, name + '.png'), fullPage });
  try {
    await page.goto('http://localhost:8080/');
    await page.getByRole('heading', { name: /LAS MEJORES/ }).waitFor();
    await page.getByRole('button', { name: 'Añadir al carrito', exact: true }).first().waitFor();
    await shot('01-home');
    await page.goto('http://localhost:8080/#/acceso');
    await page.getByRole('button', { name: 'Crear cuenta', exact: true }).click();
    await page.getByRole('button', { name: 'Crear mi cuenta' }).click();
    await page.getByText(/correo con @/).waitFor();
    await shot('02-validaciones');
    const email = `qa-ui-${crypto.randomBytes(4).toString('hex')}@example.com`;
    const password = crypto.randomBytes(12).toString('base64url');
    await page.getByLabel('Nombre', { exact: true }).fill('Cliente Presentación');
    await page.getByLabel('Correo electrónico').fill(email);
    await page.getByLabel('Contraseña', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Crear mi cuenta' }).click();
    await page.getByRole('heading', { name: /Encuentra tu próxima/ }).waitFor();
    await page.reload();
    await page.getByLabel('Cerrar sesión', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Recargar saldo virtual' }).click();
    const wallet = page.getByRole('dialog', { name: 'Recargar saldo' });
    await wallet.getByRole('radio').first().check();
    await shot('12-recarga');
    await wallet.getByRole('button', { name: 'Añadir saldo virtual' }).click();
    await wallet.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'Añadir al carrito', exact: true }).first().click();
    await page.getByRole('link', { name: /Carrito, 1/ }).click();
    await page.getByRole('button', { name: /Confirmar compra/ }).waitFor();
    await shot('03-carrito');
    await page.getByRole('button', { name: /Confirmar compra/ }).click();
    await page.getByRole('heading', { name: /Mi inventario/ }).waitFor();
    await shot('04-inventario');
    await page.getByRole('link', { name: 'Mi perfil' }).click();
    await page.getByRole('heading', {name: 'Mi perfil'}).waitFor();
    await page.getByLabel('Sobre mí').fill('Coleccionista de skins de CS2.');
    await page.getByRole('radio', {name: 'Escudo'}).check();
    await page.getByLabel('Fecha de nacimiento (opcional)').fill('1999-05-08');
    await page.getByLabel('Ubicación de perfil (opcional)').fill('Santiago, Chile');
    const demoPhoto = await page.evaluate(() => {
      const canvas = document.createElement('canvas');
      canvas.width = canvas.height = 64;
      const ctx = canvas.getContext('2d');
      ctx.fillStyle = '#6134bb';
      ctx.fillRect(0, 0, 64, 64);
      ctx.fillStyle = '#ffffff';
      ctx.font = 'bold 30px sans-serif';
      ctx.textAlign = 'center';
      ctx.textBaseline = 'middle';
      ctx.fillText('SM', 32, 32);
      return canvas.toDataURL('image/png').split(',')[1];
    });
    const photoButton = page.getByRole('button', {name: 'Cambiar foto de perfil'});
    await photoButton.hover();
    const picker = page.waitForEvent('filechooser');
    await photoButton.click();
    await (await picker).setFiles({
      name: 'avatar-demo.png', mimeType: 'image/png', buffer: Buffer.from(demoPhoto, 'base64'),
    });
    await page.getByRole('button', {name: 'Quitar foto'}).waitFor();
    await page.getByLabel('Mostrar mi saldo en el encabezado').uncheck();
    await page.getByRole('button', {name: 'Guardar cambios'}).click();
    await page.getByText('Perfil actualizado.', {exact: true}).waitFor();
    await page.reload();
    await page.getByRole('heading', {name: 'Mi perfil'}).waitFor();
    assert.equal(await page.getByLabel('Sobre mí').inputValue(), 'Coleccionista de skins de CS2.');
    assert.equal(await page.getByLabel('Mostrar mi saldo en el encabezado').isChecked(), false);
    assert.equal(await page.getByLabel('Fecha de nacimiento (opcional)').inputValue(), '1999-05-08');
    await page.getByRole('button', {name: 'Quitar foto'}).waitFor();
    await shot('11-perfil', true);
    await page.getByRole('link', { name: 'Ser vendedor' }).click();
    await page.getByLabel('Motivo para solicitar el rol').fill('Quiero obtener acceso al panel de vendedor.');
    await page.getByLabel('¿Estudias actualmente?').selectOption('yes');
    await page.getByLabel('Institución educativa (opcional)').fill('Instituto de prueba');
    await page.getByLabel('País').fill('Chile');
    await page.getByLabel('Estado, región o provincia').fill('Metropolitana');
    await page.getByLabel('Ciudad').fill('Santiago');
    await page.getByLabel('Código postal (si aplica)').fill('8320000');
    await shot('08-postulacion', true);
    await page.getByRole('button', { name: 'Enviar solicitud' }).click();
    await page.getByText('Estado: En revisión').waitFor();
    await page.getByLabel('Cerrar sesión', { exact: true }).click();
    await page.getByRole('link', { name: /Acceder/ }).click();
    await page.getByLabel('Correo electrónico').fill(env.BOOTSTRAP_ADMIN_EMAIL);
    await page.getByLabel('Contraseña', { exact: true }).fill(env.BOOTSTRAP_ADMIN_PASSWORD);
    await page.getByRole('button', { name: 'Entrar a SkinMarket' }).click();
    await page.getByRole('heading', { name: /Administración/ }).waitFor();
    await shot('05-dashboard');
    await page.getByRole('button', { name: 'Usuarios', exact: true }).click();
    await shot('06-usuarios');
    await page.getByRole('button', { name: 'Solicitudes de vendedor' }).click();
    const application = page.getByRole('article').filter({ hasText: email });
    await application.getByRole('button', { name: 'Aprobar' }).waitFor();
    await shot('09-revision');
    await application.getByRole('button', { name: 'Aprobar' }).click();
    await application.getByText('Estado: Aprobada').waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('http://localhost:8080/#/productos');
    await page.getByRole('heading', { name: /Encuentra tu próxima/ }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'La página desborda horizontalmente en móvil');
    await shot('07-movil');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByLabel('Cerrar sesión', { exact: true }).click();
    await page.getByRole('link', { name: /Acceder/ }).click();
    await page.getByLabel('Correo electrónico').fill(email);
    await page.getByLabel('Contraseña', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Entrar a SkinMarket' }).click();
    await page.getByRole('heading', { name: 'Panel de vendedor' }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Añadir al carrito' }).count(), 0);
    await page.getByRole('button', { name: 'Publicaciones', exact: true }).click();
    await page.getByRole('button', { name: 'Publicar skin', exact: true }).click();
    const selector = page.getByRole('combobox', { name: 'Skin de mi inventario' });
    await selector.selectOption({ index: 1 });
    await page.getByLabel('Precio por unidad en USD').fill('22.5');
    await shot('13-publicacion');
    const savedListing = page.waitForResponse((response) =>
      response.url().endsWith('/seller/listings') && response.request().method() === 'POST' && response.status() === 201);
    await page.getByRole('button', { name: 'Publicar en el mercado' }).click();
    const listing = await (await savedListing).json();
    await page.getByText('Skin publicada en el mercado.', { exact: true }).waitFor();

    const buyerContext = await browser.newContext();
    try {
      const buyer = await buyerContext.newPage();
      await buyer.goto('http://localhost:8080/#/acceso');
      await buyer.getByRole('button', { name: 'Crear cuenta', exact: true }).click();
      await buyer.getByLabel('Nombre', { exact: true }).fill('Cliente Reventa');
      await buyer.getByLabel('Correo electrónico').fill(`qa-resale-${crypto.randomBytes(5).toString('hex')}@example.com`);
      await buyer.getByLabel('Contraseña', { exact: true }).fill(crypto.randomBytes(16).toString('hex'));
      await buyer.getByRole('button', { name: 'Crear mi cuenta' }).click();
      await buyer.getByRole('heading', { name: /Encuentra tu próxima/ }).waitFor();
      await buyer.goto(`http://localhost:8080/#/productos/${listing.id}`);
      await buyer.getByRole('button', { name: 'Añadir al carrito', exact: true }).click();
      await buyer.getByRole('link', { name: /Carrito, 1/ }).click();
      await buyer.getByRole('button', { name: /Confirmar compra/ }).click();
      await buyer.getByRole('heading', { name: /Mi inventario/ }).waitFor();
    } finally { await buyerContext.close(); }

    await page.reload();
    await page.getByRole('heading', { name: 'Mis ventas de los últimos 7 días' }).waitFor();
    const metrics = page.locator('.seller-metrics');
    assert.equal(await metrics.evaluate((element) => getComputedStyle(element).gridTemplateColumns.split(' ').length), 4);
    await shot('10-vendedor');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await metrics.evaluate((element) => getComputedStyle(element).gridTemplateColumns.split(' ').length), 2);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'El panel de vendedor desborda en móvil');
    await page.getByRole('button', { name: 'Historial de ventas', exact: true }).click();
    await page.getByRole('link', { name: 'Ver detalle', exact: true }).first().click();
    await page.getByRole('heading', { name: 'Detalle de venta' }).waitFor();
    assert.deepEqual(errors, [], 'Errores JavaScript en el navegador');
    console.log('OK: registro, sesión, compra, inventario, postulación, aprobación, publicación, venta e historial del vendedor en móvil.');
  } finally { await browser.close(); }
})().catch((e) => { console.error(e.message); process.exitCode = 1; });
