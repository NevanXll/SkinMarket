// Verificación de navegador opcional. Instalar Playwright o indicar PLAYWRIGHT_MODULE_DIR.
const { chromium } = require(require.resolve('playwright', { paths: [process.env.PLAYWRIGHT_MODULE_DIR || process.cwd()] }));
const fs = require('node:fs');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
(async () => {
  const env = Object.fromEntries(fs.readFileSync('.env', 'utf8').split(/\r?\n/).filter((s) => s && !s.startsWith('#') && s.includes('=')).map((s) => { const i=s.indexOf('='); return [s.slice(0,i),s.slice(i+1)]; }));
  const executablePath = process.env.CHROME_BIN || ['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Google/Chrome/Application/chrome.exe'].find(fs.existsSync);
  const browser = await chromium.launch({ headless: true, executablePath });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  fs.mkdirSync('docs/screenshots', { recursive: true });
  const shot = (name) => page.screenshot({ path: `docs/screenshots/${name}.png`, fullPage: false });
  try {
    await page.goto('http://localhost:8080/');
    await page.getByRole('heading', { name: /LAS MEJORES/ }).waitFor();
    await page.getByRole('button', { name: 'Añadir al carrito', exact: true }).first().waitFor();
    await shot('01-home');
    await page.goto('http://localhost:8080/#/acceso');
    await page.getByRole('button', { name: 'Crear cuenta', exact: true }).click();
    await page.getByRole('button', { name: 'Crear mi cuenta' }).click();
    await page.getByText(/correo con @/).waitFor();
    await shot('02-validaciones');
    const email = `qa-ui-${crypto.randomBytes(4).toString('hex')}@example.com`;
    const password = crypto.randomBytes(12).toString('base64url');
    await page.getByLabel('Nombre', { exact: true }).fill('Cliente Presentación');
    await page.getByLabel('Correo electrónico').fill(email);
    await page.getByLabel('Contraseña', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Crear mi cuenta' }).click();
    await page.getByRole('heading', { name: /Encuentra tu próxima/ }).waitFor();
    await page.reload();
    await page.getByLabel('Cerrar sesión', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Añadir al carrito', exact: true }).first().click();
    await page.getByRole('link', { name: /Carrito, 1/ }).click();
    await page.getByRole('button', { name: /Confirmar compra/ }).waitFor();
    await shot('03-carrito');
    await page.getByRole('button', { name: /Confirmar compra/ }).click();
    await page.getByRole('heading', { name: /Mi inventario/ }).waitFor();
    await shot('04-inventario');
    await page.getByRole('link', { name: 'Vender skins' }).click();
    await page.getByLabel('Skins que quieres vender').fill('AK | Asiimov');
    await page.getByLabel('Motivo de la solicitud').fill('Quiero vender parte de mi colección de skins.');
    await shot('08-postulacion');
    await page.getByRole('button', { name: 'Enviar solicitud' }).click();
    await page.getByText('Estado: En revisión').waitFor();
    await page.getByLabel('Cerrar sesión', { exact: true }).click();
    await page.getByRole('link', { name: /Acceder/ }).click();
    await page.getByLabel('Correo electrónico').fill(env.BOOTSTRAP_ADMIN_EMAIL);
    await page.getByLabel('Contraseña', { exact: true }).fill(env.BOOTSTRAP_ADMIN_PASSWORD);
    await page.getByRole('button', { name: 'Entrar a SkinMarket' }).click();
    await page.getByRole('heading', { name: /Administración/ }).waitFor();
    await shot('05-dashboard');
    await page.getByRole('button', { name: 'Usuarios', exact: true }).click();
    await shot('06-usuarios');
    await page.getByRole('button', { name: 'Solicitudes de vendedor' }).click();
    const application = page.getByRole('article').filter({ hasText: email });
    await application.getByRole('button', { name: 'Aprobar' }).waitFor();
    await shot('09-revision');
    await application.getByRole('button', { name: 'Aprobar' }).click();
    await application.getByText('Estado: Aprobada').waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('http://localhost:8080/#/productos');
    await page.getByRole('heading', { name: /Encuentra tu próxima/ }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'La página desborda horizontalmente en móvil');
    await shot('07-movil');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByLabel('Cerrar sesión', { exact: true }).click();
    await page.getByRole('link', { name: /Acceder/ }).click();
    await page.getByLabel('Correo electrónico').fill(email);
    await page.getByLabel('Contraseña', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Entrar a SkinMarket' }).click();
    await page.getByRole('heading', { name: 'Panel de vendedor' }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Añadir al carrito' }).count(), 0);
    await page.getByRole('button', { name: 'Órdenes', exact: true }).click();
    await page.getByRole('link', { name: 'Ver detalle', exact: true }).first().click();
    await page.getByRole('heading', { name: 'Detalle de orden' }).waitFor();
    await shot('10-vendedor');
    assert.deepEqual(errors, [], 'Errores JavaScript en el navegador');
    console.log('OK: registro, sesión, compra, inventario, postulación, aprobación, panel de vendedor y vista móvil.');
  } finally { await browser.close(); }
})().catch((e) => { console.error(e.message); process.exitCode = 1; });
